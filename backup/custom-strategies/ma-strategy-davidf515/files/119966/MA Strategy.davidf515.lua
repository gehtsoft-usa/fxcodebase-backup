function Prepare(nameOnly)
    for _, module in pairs(Modules) do module:Prepare(nameOnly); end
    local name = profile:id() .. "( " .. instance.bid:name() .. " )";
    instance:name(name);
    if nameOnly then
        return ;
    end

    Source = ExtSubscribe(1, nil, instance.parameters.timeframe, instance.parameters.is_bid, "bar");
    TickSource = ExtSubscribe(2, nil, "t1", instance.parameters.is_bid);
    dist = instance.parameters.distance * Source:pipSize();

    assert(core.indicators:findIndicator("AVERAGES") ~= nil, "Please, download and install AVERAGES.lua indicator");          
    ma1 = core.indicators:create("AVERAGES", Source.close, instance.parameters.method_1, instance.parameters.length_1);
    ma2 = core.indicators:create("AVERAGES", Source.close, instance.parameters.method_2, instance.parameters.length_2);
end

local last_serial;
function CloseTrades(side)
    trading:FindTrade()
        :WhenInstrument(Source:instrument())
        :WhenSide(side)
        :Do(function (trade) trading:Close(trade); end);
end

function ExtUpdate(id, source, period) 
    for _, module in pairs(Modules) do if module.BlockTrading ~= nil and module:BlockTrading(id, source, period) then return; end end for _, module in pairs(Modules) do if module.ExtUpdate ~= nil then module:ExtUpdate(id, source, period); end end
    ma1:update(core.UpdateLast);
    ma2:update(core.UpdateLast);
    if last_serial == Source:serial(NOW) or Source:size() < 2 then
        return;
    end
    local lower_border = ma1.DATA[NOW] - dist;
    local upper_border = ma1.DATA[NOW] + dist;
    if Source.open[NOW] < lower_border and Source.close[NOW] >= lower_border
        and ma1.DATA[NOW] > ma1.DATA[NOW - 1] and ma2.DATA[NOW] > ma2.DATA[NOW - 1]
    then
        if instance.parameters.close_on_opposite then
            CloseTrades("S");
        end
        last_serial = Source:serial(NOW);
        if instance.parameters.allow_trade then
            local t = trading:MarketOrder(source:instrument())
                :SetSide("B")
                :SetAccountID(instance.parameters.account)
                :SetAmount(instance.parameters.amount);
            if instance.parameters.use_stop then
                t = t:SetPipStop(nil, instance.parameters.stop, instance.parameters.trailing_stop and instance.parameters.trailing or nil);
            end
            if instance.parameters.set_limit then
                t = t:SetPipLimit(nil, instance.parameters.limit);
            end
            t:Execute();
        end
        signaler:Signal("Buy");
    elseif Source.open[NOW] > upper_border and Source.close[NOW] <= upper_border
        and ma1.DATA[NOW] < ma1.DATA[NOW - 1] and ma2.DATA[NOW] < ma2.DATA[NOW - 1]
    then
        if instance.parameters.close_on_opposite then
            CloseTrades("B");
        end
        last_serial = Source:serial(NOW);
        if instance.parameters.allow_trade then
            local t = trading:MarketOrder(source:instrument())
                :SetSide("S")
                :SetAccountID(instance.parameters.account)
                :SetAmount(instance.parameters.amount);
            if instance.parameters.use_stop then
                t = t:SetPipStop(nil, instance.parameters.stop, instance.parameters.trailing_stop and instance.parameters.trailing or nil);
            end
            if instance.parameters.set_limit then
                t = t:SetPipLimit(nil, instance.parameters.limit);
            end
            t:Execute();
        end
        signaler:Signal("Sell");
    end
end

