function ParseTime(time)
    local pos = string.find(time, ":");
    if pos == nil then
        return nil, false;
    end
    local h = tonumber(string.sub(time, 1, pos - 1));
    time = string.sub(time, pos + 1);
    pos = string.find(time, ":");
    if pos == nil then
        return nil, false;
    end
    local m = tonumber(string.sub(time, 1, pos - 1));
    local s = tonumber(string.sub(time, pos + 1));
    return (h / 24.0 +  m / 1440.0 + s / 86400.0),                          -- time in ole format
           ((h >= 0 and h < 24 and m >= 0 and m < 60 and s >= 0 and s < 60) or (h == 24 and m == 0 and s == 0)); -- validity flag
end

function InRange(now, openTime, closeTime)
    if openTime < closeTime then
        return now >= openTime and now <= closeTime;
    end
    if openTime > closeTime then
        return now > openTime or now < closeTime;
    end

    return now == openTime;
end

function ExtUpdate(id, source, period) -- The method called every time when a new bid or ask price appears.
    for _, module in pairs(Modules) do if module.ExtUpdate ~= nil then module:ExtUpdate(id, source, period); end end
    if AllowTrade then
        if not (checkReady("trades")) or not (checkReady("orders")) then
            return
        end
    end

    if id ~= 1 then
        return
    end

    Indicator["MACD"]:update(core.UpdateLast)
    Indicator["CCI"]:update(core.UpdateLast)

    if period < first + 1 then
        return
    end

    now = core.host:execute("getServerTime")
    now = core.host:execute("convertTime", core.TZ_EST, ToTime, now)
    -- get only time
    now = now - math.floor(now)

    if not InRange(now, OpenTime, CloseTime) then
        return
    end

    --  buying condition:

    --1. cci [period14] > buy level { and}
    --2. macd line cross over signal line { and}
    --3. signal line < buy level {0}

    if Short["CCI"][period] > CB and Short["MACD"][period] > Short["SIGNAL"][period] and Short["SIGNAL"][period] < MB then
        --selling condition:
        --1. cci [ period 14] < sell level{ and }
        --2. macd line cross under signal line { and }
        --3. signal line < sell level {0}
        if Direction then
            BUY()
        else
            SELL()
        end
    elseif
        Short["CCI"][period] < CS and Short["MACD"][period] < Short["SIGNAL"][period] and Short["SIGNAL"][period] > MS
     then
        if Direction then
            SELL()
        else
            BUY()
        end
    end

    --  exit buy conditions:

    --1. cci cross below buy level { or}
    --2. macd line cross under signal line

    if core.crossesUnder(Short["CCI"], CB, period) or core.crossesUnder(Short["MACD"], Short["SIGNAL"], period) then
        if Direction then
            if haveTrades("B") then
                exit("B")
                Signal("Close Long")
            end
        else
            if haveTrades("S") then
                exit("S")
                Signal("Close Short")
            end
        end
    end

    --exit sell conditions:

    --1. cci cross above sell level {or}
    --2. macd line cross above signal line

    if core.crossesOver(Short["CCI"], CS, period) or core.crossesOver(Short["MACD"], Short["SIGNAL"], period) then
        if Direction then
            if haveTrades("S") then
                exit("S")
                Signal("Close Short")
            end
        else
            if haveTrades("B") then
                exit("B")
                Signal("Close Long")
            end
        end
    end
end

-- NG: Introduce async function for timer/monitoring for the order results
function ExtAsyncOperationFinished(cookie, success, message)
    for _, module in pairs(Modules) do if module.AsyncOperationFinished ~= nil then module:AsyncOperationFinished(cookie, success, message, message1, message2); end end
    if cookie == 100 then
        -- timer
        if UseMandatoryClosing and AllowTrade then
            now = core.host:execute("getServerTime")
            now = core.host:execute("convertTime", core.TZ_EST, ToTime, now)
            -- get only time
            now = now - math.floor(now)

            -- check whether the time is in the exit time period
            if now >= ExitTime and now < ExitTime + (ValidInterval / 86400.0) then
                if not checkReady("trades") then
                    return
                end

                if haveTrades("B") then
                    exit("B")
                    Signal("Close Long")
                end

                if haveTrades("S") then
                    exit("S")
                    Signal("Close Short")
                end
            end
        end
    elseif cookie == 200 and not success then
        terminal:alertMessage(
            instance.bid:instrument(),
            instance.bid[instance.bid:size() - 1],
            "Open order failed" .. message,
            instance.bid:date(instance.bid:size() - 1)
        )
    elseif cookie == 201 and not success then
        terminal:alertMessage(
            instance.bid:instrument(),
            instance.bid[instance.bid:size() - 1],
            "Close order failed" .. message,
            instance.bid:date(instance.bid:size() - 1)
        )
    end
end

