function Update(period, mode)
   if period<first then
   return;
   end
   
    MA_O:update(mode);
    MA_H:update(mode);
    MA_L:update(mode);
    MA_C:update(mode);

    MA_O2:update(mode);
    MA_H2:update(mode);
    MA_L2:update(mode);
    MA_C2:update(mode);
    
    local X_O = 2*MA_O2.DATA[period]-MA_O.DATA[period];
    local X_H = 2*MA_H2.DATA[period]-MA_H.DATA[period];
    local X_L = 2*MA_L2.DATA[period]-MA_L.DATA[period];
    local X_C = 2*MA_C2.DATA[period]-MA_C.DATA[period];
    
    high[period] = math.max(X_H, open[period-1], close[period-1]);
    low[period] = math.min(X_L, open[period-1], close[period-1]);
    open[period] = (open[period-1]+close[period-1])/2;
    close[period] = (X_O+X_H+X_L+X_C)/4;
	
	
	Activate (1, period);
 
end



function Activate (id, period)


   Alert[id][period]=0;
   
   
  
  
	  if id == 1  and ON[id]  then
	  
	       
			if  close[period] > open[period] 
			and   close[period-1] <= open[period-1] 
			then
			           
						    
         
                Alert[id][period]= 1;	
 				AlertLevel[id][period]= low[period] 
						   
			
			 D[id] = nil;
						   
							  if U[id]~=source:serial(period) 
							  and period == source:size()-1-Shift
							  and not FIRST 
							  and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							  then
							  
							  U[id]=source:serial(period);
							  SoundAlert(Up[id]);
							  EmailAlert(  Label[id], " UP ", period);
							  SendAlert( Label[id]," UP ", period); 
							  Pop(Label[id], " UP ", period );  
							  OnlyOnceFlag=false;
							  end
							  
			elseif  close[period] < open[period] 
			and   close[period-1] >= open[period-1] 
            then			
			
			            			 
			                Alert[id][period]= -1;	
							AlertLevel[id][period]= high[period] 
						   
		     U[id] = nil;
		   
			                 if  D[id]~=source:serial(period)
							 and period == source:size()-1-Shift
							 and not FIRST 
							 and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							 then							
							 D[id]=source:serial(period);
							 SoundAlert(Down[id]);			 
							 EmailAlert( Label[id] , " DOWN ", period);								 
							 Pop(Label[id], " DOWN ", period );  	
							 SendAlert( Label[id]," DOWN ", period);
							 OnlyOnceFlag=false;
			                 end			   
	         end
			
	  
	 
	  end
	  
		   
        if FIRST then
        FIRST=false;      
        end		

end


