function Signal_Logic (id, period)


       
	  --  if not Show_Unconfirmed then
	   -- Alert[id][period]= 0;	
		--end
  
	
	  
	    if id== 1  then   
			if  Trend[period]==1 
			and   Trend[period-1]~=1
			then
			           
						    
         
                Alert[id][period]= 1;	
 				AlertLevel[id][period]= Bottom[period] 
				Alignment[id][period]= -1;		   
					
						   							  
			elseif  Trend[period]==-1 
			and   Trend[period-1]~=-1
            then			
			 
						   
		  
		     Alert[id][period]= 0;
			                
	         end
			
	    end
		
		
		if id== 2   then  
			if  Trend[period]==-1 
			and   Trend[period-1]~=-1
			then
			           
						    
         
                Alert[id][period]= 1;	
 				AlertLevel[id][period]= Top[period] 
				Alignment[id][period]= 1;		   
			
						   
							  							  
			elseif  Trend[period]==1 
			and   Trend[period-1]~=1
            then			
			 
		 
		     Alert[id][period]= 0;
			                
	         end
			
	    end


end

