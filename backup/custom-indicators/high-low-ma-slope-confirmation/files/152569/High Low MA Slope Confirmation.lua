-- Routine
 function Prepare(nameOnly)   
 
    local name = profile:id() .. "(" ..  instance.source:name()  .. ")";
    instance:name(name); 


    if   (nameOnly) then
        return;
    end

   Up = instance.parameters.Up;
   Down= instance.parameters.Down;
   Neutral= instance.parameters.Neutral;
   
   Lines= instance.parameters.Lines;
   Transparency= instance.parameters.Transparency;
   Transparency= 100-Transparency;
			
	Period1= instance.parameters.Period1;
    Method1= instance.parameters.Method1;
	
	Period2= instance.parameters.Period2;
    Method2= instance.parameters.Method2;
			
    source = instance.source;

    assert(core.indicators:findIndicator("AVERAGES") ~= nil, "Please, download and install AVERAGES.LUA indicator");    
  
    Indicator[1] = core.indicators:create("AVERAGES", source["high"], Method1,  Period1);
    Indicator[2] = core.indicators:create("AVERAGES", source["low"], Method2, Period2);
    
    first=math.max(Indicator[1].DATA:first(), Indicator[2].DATA:first());
	
    Trend = instance:addInternalStream(0, 0);	
 
	 
   if Lines then   
   Top=instance:addStream("Top", core.Line, name, "Top", core.rgb( 128, 128, 128), first);
   Bottom=instance:addStream("Bottom", core.Line, name, "Bottom", core.rgb( 128, 128, 128), first);
   else
   Top=instance:addInternalStream(first, 0);     
   Bottom=instance:addInternalStream(first, 0);
   end
	
	
	instance:createChannelGroup("Group","Group" , Top, Bottom, Neutral, Transparency);
	
	
--//////////////////////////////////////////////////////////////////////////////
--\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\



   
   	Alert_Triger= instance.parameters.Alert_Triger;
	
	 
 
    if Alert_Triger ~= "Timer" then
    core.host:execute("subscribeTradeEvents", 1, "offers");
    end
	

	
	Timer= instance.parameters.Timer 
	Initialization();	
	instance:ownerDrawn(true);	
	
	if Alert_Triger ~= "Price" then
    core.host:execute ("setTimer", 3 , Timer);
	end
			
end 

function ReleaseInstance()
core.host:execute ("killTimer", 3 );
end 
 

-- Indicator calculation routine
function Update(period, mode)
      
    Indicator[1]:update(mode);
    Indicator[2]:update(mode);
	
		
	if  not Indicator[1].DATA:hasData(period) or  not Indicator[2].DATA:hasData(period) then 
		return;
	end
	
	Top[period] = Indicator[1].DATA[period];
	Bottom[period] = Indicator[2].DATA[period]; 
	
	
	local Slope1= Indicator[1].DATA[period]-Indicator[1].DATA[period-1];
	local Slope2= Indicator[2].DATA[period]-Indicator[2].DATA[period-1];

	if  Slope1 > 0 and Slope2 > 0 then
	Trend[period]=1;
	elseif  Slope1 < 0 and Slope2 < 0 then
	Trend[period]=-1;	
	else
	Trend[period]=Trend[period-1];	
	end
	
      
				if Trend[period]==1 then 
				Top:setColor(period, Up);
				elseif  Trend[period]==-1  then
				Top:setColor(period, Down);	
				else
				Top:setColor(period, Neutral);
				end
		

	if Signal_Execution~= "Live" then
	period=period-1;	 
	end
	

    for id=1, Number, 1 do
    Signal_Logic (id, period);
	end				  
end


