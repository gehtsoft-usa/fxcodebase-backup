function Init()
    indicator:name("Right Sided Ricker Moving Average And The Gaussian Derivatives");
    indicator:description("");
    indicator:requiredSource(core.Tick);
    indicator:type(core.Indicator);

  
 	indicator.parameters:addGroup("Calculation");	
    indicator.parameters:addInteger("length", "Fast MA", "", 50, 1, 2000);
    indicator.parameters:addInteger("pw", "Percent Width", "", 60, 0, 100);
	
	 indicator.parameters:addGroup("Line Style");	
    indicator.parameters:addInteger("width", "Line width", "", 1, 1, 5);
    indicator.parameters:addInteger("style", "Line style", "", core.LINE_SOLID);
    indicator.parameters:setFlag("style", core.FLAG_LINE_STYLE);
	
	 indicator.parameters:addColor("color", "Line Color", "", core.rgb(0, 0, 255)); 
 
end

-- Indicator instance initialization routine
-- Processes indicator parameters and creates output streams
-- TODO: Refine the first period calculation for each of the output streams.
-- TODO: Calculate all constants, create instances all subsequent indicators and load all required libraries
-- Parameters block
 
	
local first;
local source = nil;
local length, pw; 
local width;
	
-- Routine
 function Prepare(nameOnly)   
 
    
	length=instance.parameters.length;
	pw=instance.parameters.pw;
	source = instance.source
	
	width = pw/100*length
 
    local name = profile:id() .. "(" ..  instance.source:name().. "," ..  length.. "," ..  pw  .. ")";
    instance:name(name); 


    if   (nameOnly) then
        return;
    end
	
 
	first=source:first() ; 
	
	
 
 
	
	
    Line = instance:addStream("Line", core.Line, name, "Line", instance.parameters.color, first );
    Line:setPrecision(math.max(2, instance.source:getPrecision()));
    Line:setWidth(instance.parameters.width);
    Line:setStyle(instance.parameters.style);
    Line:addLevel(0);	
 
end


function Update(period, mode)

    local sum = 0.;
	local sumw = 0.;

	 if period <= first then
	 return;
	 end
	 
 
	for i = 0 ,length-1, 1 do
    w = (1 - math.pow(i/width,2))*math.exp(-(i*i/(2*math.pow(width,2))))
    sumw = sumw + w;
    sum = sum + source[period-i] * w;
	end
	
	Line[period]= sum/sumw;
	
end


 