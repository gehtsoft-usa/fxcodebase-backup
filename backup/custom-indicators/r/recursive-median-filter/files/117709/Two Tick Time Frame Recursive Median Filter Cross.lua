-- Indicator calculation routine
function Update(period, mode)

   
    if period < first then
	return;
	end
	 
	
	local P1= core.findDate (source, source:date(period)- Second * Period1, false);
	local P2= core.findDate (source, source:date(period)- Second * Period2, false);
	
	local P3= core.findDate (source, source:date(period)- Second * Period3, false);
	local P4= core.findDate (source, source:date(period)- Second * Period4, false);

	if P1==-1
	or P1< first+1 
	or P2==-1
	or P2< first+1 	
	or P3==-1
	or P3< first+1 
	or P4==-1
	or P4< first+1	
    then
    return;
    end 
	
	local angle;	
	--Set EMA constant from LPPeriod input
    angle = 2 * PI / (period-P1);	
    alpha = ( math.cos( angle ) + math.sin( angle ) - 1 )/math.cos( angle );
		
	local Median;
    --Recursive Median (EMA of a 5 bar Median filter)
	 Median = mathex.median_s(source, P2, period);
	 RM1[period] = alpha *Median  + (1 - alpha )*RM1[period-1];
	 
	 
	 local angle;	
	--Set EMA constant from LPPeriod input
    angle = 2 * PI / (period-P3);	
    alpha = ( math.cos( angle ) + math.sin( angle ) - 1 )/math.cos( angle );
		
	local Median;
    --Recursive Median (EMA of a 5 bar Median filter)
	 Median = mathex.median_s(source, P4, period);
	 RM2[period] = alpha *Median  + (1 - alpha )*RM2[period-1];
	 
	 
	 
	 if Live~= "Live" then
	period=period-1;
	Shift=1;
	else
	Shift=0;
	end
	
	
     if period < first then
	 return;
	 end
	 
	
     Activate (1, period);
end



function Activate (id, period)


   Alert[id][period]=0;
   
   
  
  
	  if id == 1  and ON[id]  then
	  
	       
			if  RM1[period] > RM2[period] 
			and   RM1[period-1] <= RM2[period-1] 
			then
			           
						    
         
                Alert[id][period]= 1;	
 				AlertLevel[id][period]= RM2[period] 
						   
			
			 D[id] = nil;
						   
							  if U[id]~=source:serial(period) 
							  and period == source:size()-1-Shift
							  and not FIRST 
							  and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							  then
							  
							  U[id]=source:serial(period);
							  SoundAlert(Up[id]);
							  EmailAlert(  Label[id], " Cross Over ");
							  SendAlert( Label[id]," Crossed over "); 
							  Pop(Label[id], " Cross Over ", period );  
							  OnlyOnceFlag=false;
							  end
							  
			elseif  RM1[period] < RM2[period] 
			and   RM1[period-1] >= RM2[period-1] 
            then			
			
			            			 
			                Alert[id][period]= -1;	
							AlertLevel[id][period]= RM2[period] 
						   
		     U[id] = nil;
		   
			                 if  D[id]~=source:serial(period)
							 and period == source:size()-1-Shift
							 and not FIRST 
							 and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							 then							
							 D[id]=source:serial(period);
							 SoundAlert(Down[id]);			 
							 EmailAlert( Label[id] , " Cross Under ");								 
							 Pop(Label[id], " Cross Under ", period );  	
							 SendAlert( Label[id]," Crossed under ");
							 OnlyOnceFlag=false;
			                 end			   
	         end
			
	  
	 
	  end
	  
		   
        if FIRST then
        FIRST=false;      
        end		

end


