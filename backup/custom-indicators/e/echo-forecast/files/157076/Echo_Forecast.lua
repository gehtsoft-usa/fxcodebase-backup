    vars["showArea"] = instance.parameters.param8;
    vars["refArea"] = Graphics:AddTransparency(instance.parameters.param9, Graphics:GetTransparencyPercent(core.rgb(255, 93, 0) + math.floor(80 / 100 * 255) * 16777216));
    vars["corrArea"] = Graphics:AddTransparency(instance.parameters.param10, Graphics:GetTransparencyPercent(core.rgb(8, 153, 129) + math.floor(80 / 100 * 255) * 16777216));
    vars["evalArea"] = Graphics:AddTransparency(instance.parameters.param11, Graphics:GetTransparencyPercent(core.colors().Gray + math.floor(80 / 100 * 255) * 16777216));
    vars["__IsFirst1"] = CreateIsFirst();
    Line:Prepare(200);
    vars["n"] = instance:addInternalStream(0, 0);
    vars["d"] = instance:addInternalStream(0, 0);
    instance:ownerDrawn(true);
