function Update(period, mode)
    if period == 0 or mode == core.UpdateAll then
        Line:Clear();
        Box:Clear();
        vars["lines"] = Array:NewLine(0, nil);
        vars["eval_window"] = Box:New(core.formatDate(source:date(0)), "1", nil, nil, nil, nil):SetBgColor(vars["evalArea"]):SetBorderColor(nil);
        vars["ref_window"] = Box:New(core.formatDate(source:date(0)), "2", nil, nil, nil, nil):SetBgColor(vars["refArea"]):SetBorderColor(nil);
        vars["corr_window"] = Box:New(core.formatDate(source:date(0)), "3", nil, nil, nil, nil):SetBgColor(vars["corrArea"]):SetBorderColor(nil);
    else
        vars["__IsFirst1"]:Clear();
    end
    PineScriptUtils:UpdateSources(period, mode);
    if vars["__IsFirst1"]:IsFirst() then
        local for1_from = 0;
        local for1_to = vars["fcast"] - 1;
        local for1_step = for1_from > for1_to and 1 or -1;
        if not for1_from or not for1_to then return; end
        for i = for1_from, for1_to, for1_step do
            vars["lines"]:Push(Line:New(nil, nil, nil, nil):SetColor(vars["fcastCss"]):SetStyle(Triary((vars["fcastStyle"] == "- - -"), "dashed", Triary((vars["fcastStyle"] == "? ? ?"), "dotted", "solid"))));
        end
    end
    SafeSetFloat(vars["n"], period, period);
    SafeSetFloat(vars["d"], period, SafeMinus(vars["src"]:tick(period), vars["src"]:tick(period - 1)));
    if vars["src"]:first() > period - (vars["length"] + vars["fcast"] * 2) then return; end
    top = mathex.max(vars["src"], core.rangeTo(period, vars["length"] + vars["fcast"] * 2));
    if vars["src"]:first() > period - (vars["length"] + vars["fcast"] * 2) then return; end
    btm = mathex.min(vars["src"], core.rangeTo(period, vars["length"] + vars["fcast"] * 2));
    if period == source:size() - 1 then
        vars["k"] = 0;
        vars["val"] = nil;
        A = Array:NewFloat(0, nil);
        X = Array:NewInt(0, nil);
        local for2_from = 0;
        local for2_to = vars["fcast"] * 2 + vars["length"];
        local for2_step = for2_from > for2_to and 1 or -1;
        if not for2_from or not for2_to then return; end
        for i = for2_from, for2_to, for2_step do
            A:Push(vars["src"]:tick(period - i));
            if (vars["cmode"] == "Linreg") then
                if vars["n"]:first() > period - (i) then return; end
                X:Push(SafeGetFloat(vars["n"], period - i));
            end
        end
        a = A:Slice(0, vars["fcast"] - 1);
        local for3_from = 0;
        local for3_to = vars["length"] - 1;
        local for3_step = for3_from > for3_to and 1 or -1;
        if not for3_from or not for3_to then return; end
        for i = for3_from, for3_to, for3_step do
            b = A:Slice(vars["fcast"] + i, vars["fcast"] * 2 + i - 1);
            r = SafeDivide(Array:Covariance(a, b), (SafeMultiply(a:Stdev(), b:Stdev())));
            if (vars["fmode"] == "Similarity") then
                vars["val"] = Triary(SafeGE(r, Nz(vars["val"], r)), r, vars["val"]);
            else
                vars["val"] = Triary(SafeLE(r, Nz(vars["val"], r)), r, vars["val"]);
            end
            vars["k"] = Triary((vars["val"] == r), i, vars["k"]);
        end
        prev = vars["src"]:tick(period);
        current = vars["src"]:tick(period);
        local for4_from = 0;
        local for4_to = vars["fcast"] - 1;
        local for4_step = for4_from > for4_to and 1 or -1;
        if not for4_from or not for4_to then return; end
        for i = for4_from, for4_to, for4_step do
            if vars["d"]:first() > period - (vars["fcast"] + vars["k"] + (vars["fcast"] - i - 1)) then return; end
            e = SafeGetFloat(vars["d"], period - vars["fcast"] + vars["k"] + (vars["fcast"] - i - 1));
            if (vars["cmode"] == "Mean") then
                current = SafePlus(a:Avg(), e);
            elseif (vars["cmode"] == "Linreg") then
                a = A:Slice(0, vars["fcast"]);
                x = X:Slice(0, vars["fcast"]);
                alpha = SafeDivide(Array:Covariance(a, x), Array:Variance(x));
                beta = SafeMinus(a:Avg(), SafeMultiply(alpha, x:Avg()));
                current = SafePlus(SafePlus(SafeMultiply(alpha, (SafeGetFloat(vars["n"], period) + i + 1)), beta), e);
            else
                current = SafePlus(current, e);
            end
            l = Array:Get(vars["lines"], i);
            Line:SetXY1(l, SafeGetFloat(vars["n"], period) + i, prev);
            Line:SetXY2(l, SafeGetFloat(vars["n"], period) + i + 1, current);
            prev = current;
        end
        if vars["showArea"] then
            Box:SetLeftTop(vars["eval_window"], SafeGetFloat(vars["n"], period) - vars["length"] - vars["fcast"] * 2 + 1, top);
            Box:SetRightBottom(vars["eval_window"], SafeGetFloat(vars["n"], period) - vars["fcast"] + 1, btm);
            Box:SetLeftTop(vars["ref_window"], SafeGetFloat(vars["n"], period) - vars["fcast"] + 1, top);
            Box:SetRightBottom(vars["ref_window"], SafeGetFloat(vars["n"], period), btm);
            Box:SetLeftTop(vars["corr_window"], SafeGetFloat(vars["n"], period) - vars["k"] - vars["fcast"] * 2 + 1, top);
            Box:SetRightBottom(vars["corr_window"], SafeGetFloat(vars["n"], period) - vars["k"] - vars["fcast"], btm);
        end
    end
end
