    source = instance.source;
    local name = string.format("%s(%s)", profile:id(), source:name());
    instance:name(name);
    if nameOnly then
        return;
    end
    vars["length"] = instance.parameters.param1;
    vars["fcast"] = instance.parameters.param2;
    vars["fmode"] = instance.parameters.param3;
    vars["cmode"] = instance.parameters.param4;
    vars["src"] = PineScriptUtils:CreateSource(source, instance.parameters.param5);
    vars["fcastCss"] = Graphics:AddTransparency(instance.parameters.param6, Graphics:GetTransparencyPercent(Graphics:AddTransparency(core.rgb(33, 87, 243), 0)));
