        return;
    end

	assert(core.indicators:findIndicator("AVERAGES") ~= nil, "Please, download and install AVERAGES.LUA indicator");
	 
    HMA = core.indicators:create("AVERAGES", source.high, Method, Period, false);
    LMA = core.indicators:create("AVERAGES", source.low, Method, Period, false);
	
	 first = math.max(HMA.DATA:first(),LMA.DATA:first() );
	 
	trend=instance:addInternalStream(first, 0);
	
	Line= instance:addStream("Line", core.Line, name .. ".Line", "Line", instance.parameters.UPclr, first);
	Line:setWidth(instance.parameters.widthLinReg);
    Line:setStyle(instance.parameters.styleLinReg);
	
	
	 for i= 1, Number , 1 do
		Alert[i]=instance:addInternalStream(0, 0);
		AlertLevel[i]=instance:addInternalStream(0, 0);
     end
	
	Initialization();	
	instance:ownerDrawn(true);	 
	

end

function Update(period, mode)
  
    HMA:update(mode);
    LMA:update(mode);
	
	
	if period<first then
	return;
    end
	
    if source.close[period]>HMA.DATA[period-1] then
     trend[period]=1;
    elseif source.close[period]<LMA.DATA[period-1] then
     trend[period]=-1;
    else
     trend[period]=trend[period-1];
    end
	
	
	
    if trend[period]==-1 then 
    
	   if not(NRTR)  or trend[period-1]~=-1 then
      Line[period]=HMA.DATA[period-1];	 
	  elseif NRTR then
	  Line[period]=math.min(HMA.DATA[period-1], Line[period-1]);
	  end
  
    else
          if not(NRTR)  or trend[period-1]~=1 then
          Line[period]=LMA.DATA[period-1];
          elseif NRTR then
		  Line[period]=math.max(LMA.DATA[period-1], Line[period-1]);
		  end
    end
	
	if trend[period]~= trend[period-1] then
	Line:setBreak (period, true);
	else
	Line:setBreak (period, false);
	end
	
	if trend[period]==1 then
	Line:setColor(period, instance.parameters.UPclr);
	else
	Line:setColor(period, instance.parameters.DNclr);
	end
	
	
	 
    if Live~= "Live" then
	period=period-1;
	Shift=1;
	else
	Shift=0;
	end 
	
    Activate (1, period)
 
 
end


