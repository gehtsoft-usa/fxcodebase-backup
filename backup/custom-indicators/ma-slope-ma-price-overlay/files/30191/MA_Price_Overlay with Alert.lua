-- Indicator calculation routine
function Update(period, mode)
	
    open[period] = source.open[period];
	close[period] = source.close[period];
	high[period] = source.high[period];
	low[period] = source.low[period];
	
			if period < first then
			open:setColor(period, instance.parameters.No);	
			return;
			end
	


		 MA:update(mode);
			 
		 
	if Type == "Slope" then
	
		if MA.DATA[period]> MA.DATA[period-1] then		
		open:setColor(period, instance.parameters.Up);
		Alert[1][period]=1;
        elseif  MA.DATA[period]< MA.DATA[period-1]  then
		open:setColor(period, instance.parameters.Dn);
		Alert[1][period]=-1;
		else
		open:setColor(period, instance.parameters.No);		
        Alert[1][period]=0;		
		end
		
	elseif Type == "Cross" then

        if  source[Price][period] > MA.DATA[period] then		
		open:setColor(period, instance.parameters.Up);
		Alert[1][period]=1;
        elseif source[Price][period] < MA.DATA[period]  then
		open:setColor(period, instance.parameters.Dn);
		Alert[1][period]=-1;
		else
		open:setColor(period, instance.parameters.No);		
        Alert[1][period]=0;		
		end	
		
	end	
	
	   if Live~= "Live" then
	period=period-1;
	Shift=1;
	else
	Shift=0;
	end
	
	 
    Activate (1, period);
 
 end
 
 
 
function Activate (id, period)


  
   
   
  
  
	  if id == 1  and ON[id]  then
	  
	       
			if  Alert[id][period]== 1
			and   Alert[id][period-1]~=  1
			then
			           
						    
         
                	
 				AlertLevel[id][period]= source.low[period] 
						   
			
			 D[id] = nil;
						   
							  if U[id]~=source:serial(period) 
							  and period == source:size()-1-Shift
							  and not FIRST 
							  and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							  then
							  
							  U[id]=source:serial(period);
							  SoundAlert(Up[id]);
							  EmailAlert(  Label[id], " Up Trend ", period);
							  SendAlert( Label[id]," Up Trend", period); 
							  Pop(Label[id], " Up Trend ", period );  
							  OnlyOnceFlag=false;
							  end
							  
			elseif  Alert[id][period]==  -1
			and   Alert[id][period-1] ~=  -1
            then			
			
			            			 
			                Alert[id][period]= -1;	
							AlertLevel[id][period]= source.high[period] 
						   
		     U[id] = nil;
		   
			                 if  D[id]~=source:serial(period)
							 and period == source:size()-1-Shift
							 and not FIRST 
							 and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							 then							
							 D[id]=source:serial(period);
							 SoundAlert(Down[id]);			 
							 EmailAlert( Label[id] , " Down Trend ", period);								 
							 Pop(Label[id], " Down Trend ", period );  	
							 SendAlert( Label[id]," Down Trend ", period);
							 OnlyOnceFlag=false;
			                 end			   
	         end
			
	  
	 
	  end
	  
 
		   
        if FIRST then
        FIRST=false;      
        end		

end


