function Update(period, mode)
    tema:update(mode);
    middle[period] = tema.DATA[period];
    local diff = (source.close[period] - middle[period]) / source:pipSize();
    if period == 1 then
        wu[period] = math.pow(diff, 2) / FullLength;
        wd[period] = math.pow(diff, 2) / FullLength;
    else
        if diff >= 0 then
            wu[period] = wu[period - 1] / (FullLength - 1) + math.pow(diff, 2) / FullLength;
            wd[period] = wd[period - 1];
        else
            wd[period] = wd[period - 1] / (FullLength - 1) + math.pow(diff, 2) / FullLength;
            wu[period] = wu[period - 1];
        end
    end
    upper[period] = middle[period] + BandsDeviations * math.sqrt(wu[period]) * source:pipSize();
    lower[period] = middle[period] - BandsDeviations * math.sqrt(wd[period]) * source:pipSize();

    for _, alert in ipairs(indi_alerts.Alerts) do Activate(alert, period, period ~= source:size() - 1); end
end

function Activate(alert, period, historical_period)
    if indi_alerts.Live ~= "Live" then period = period - 1; end
    alert.Alert[period] = 0;
    if not alert.ON then
        return;
    end
    local isUp, upMetadata = alert.UpCondition(period);
    if isUp then
        if alert.OnChange then
            local isUpPrev, _ = alert.UpCondition(period - 1);
            if isUpPrev then
                return;
            end
        end
        alert:UpAlert(source, period, source.high[period], historical_period, upMetadata);
        return;
    end
    local isDown, downMetadata = alert.DownCondition(period);
    if isDown then
        if alert.OnChange then
            local isDownPrev, _ = alert.DownCondition(period - 1);
            if isDownPrev then
                return;
            end
        end
        alert:DownAlert(source, period, source.low[period], historical_period, downMetadata);
    end
end

