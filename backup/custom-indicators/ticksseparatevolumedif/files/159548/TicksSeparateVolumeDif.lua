function Init()
    indicator:name("Ticks Separate Volume Dif");
    indicator:description("description");
    indicator:requiredSource(core.Bar);
    indicator:type(core.Oscillator);

    indicator.parameters:addColor("up_color", "Up color", "", core.colors().Green);
    indicator.parameters:addColor("dn_color", "Down color", "", core.colors().Red);
end

local source;
local hist;
local up_color, dn_color;
function Prepare(nameOnly)
    up_color = instance.parameters.up_color;
    dn_color = instance.parameters.dn_color;
    source = instance.source;
    local name = string.format("%s(%s)", profile:id(), source:name());
    instance:name(name);
    if nameOnly then
        return ;
    end

    hist = instance:addStream("hist", core.Bar, "Histogram", "Histogram", core.colors().Red, 0, 0);
end

function Update(period, mode)
    hist[period] = (source.volume[period] + (source.close[period] - source.open[period]) / 2.0 / source:pipSize())
        - (source.volume[period] - (source.close[period] - source.open[period]) / 2.0 / source:pipSize());
    hist:setColor(period, hist[period] > 0 and up_color or dn_color);
end

