function CreateAverages(method, source, period)
    if method == "MVA" or method == "EMA" or method == "ARSI" 
        or method == "KAMA" or method == "LWMA" or method == "SMMA"
        or method == "VIDYA"
    then
        --assert(core.indicators:findIndicator(method) ~= nil, method .. " indicator must be installed");
        return core.indicators:create(method, source, period);
    end
    assert(core.indicators:findIndicator("AVERAGES") ~= nil, "Please, download and install AVERAGES indicator");
    return core.indicators:create("AVERAGES", source, method, period);
end

local source;
local adx, avg, out,ADX;
function Prepare(nameOnly)
    source = instance.source;
    local name = string.format("%s(%s)", profile:id(), source:name());
    instance:name(name);
    if nameOnly then
        return ;
    end
    
    adx = core.indicators:create("ADX", source, instance.parameters.adx_period);
    avg = CreateAverages(instance.parameters.method, adx.DATA, instance.parameters.period);

    out = instance:addStream("out", core.Line, "MA", "MA", instance.parameters.color2,avg.DATA:first())
	out:setWidth(instance.parameters.width2);
    out:setStyle(instance.parameters.style2);
	out:setPrecision(math.max(2, instance.source:getPrecision()));
	
	ADX = instance:addStream("ADX", core.Line, "ADX", "ADX", instance.parameters.color1, avg.DATA:first())
	ADX:setWidth(instance.parameters.width1);
    ADX:setStyle(instance.parameters.style1);
	
	ADX:addLevel(instance.parameters.overbought, instance.parameters.level_overboughtsold_style, instance.parameters.level_overboughtsold_width, instance.parameters.level_overboughtsold_color);
    ADX:setPrecision(math.max(2, instance.source:getPrecision()));
end

function Update(period, mode)
    adx:update(mode);
    avg:update(mode);
	
	if period < avg.DATA:first() then
	return;
	end
	
	ADX[period] = adx.DATA[period];
    out[period] = avg.DATA[period];
end