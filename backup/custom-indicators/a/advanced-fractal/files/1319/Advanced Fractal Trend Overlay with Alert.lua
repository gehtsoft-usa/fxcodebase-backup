end 



function Update(period, mode)
 
    high[period]= source.high[period];
	low[period]= source.low[period];		   
	close[period] = source.close[period];
	open[period]  = source.open[period];	

      
 
    if (period < Fractal) then
	return;
	end
	

		 
	
	
  if (period <= Fractal) then
	return;
	end
	
	up_signal[period]=0;
	down_signal[period]=0;	
	
	     local x = period - Fractal; 
		
      local test=true;		
         for i= 1, Fractal, 1 do
		
		     if  source.high[x]  < source.high[x+i]
			 or  source.high[x] < source.high[x-i]
			 then
			 test=false;			 
			 end
			
		 end	
		 
		 if test then
		   if Show ~= "Overlay" then
 		   up:set(period - Fractal, source.high[x], "\226");
		   end
		   UP= source.high[x]; 
		 
		   up_signal[period]=1;  
		 end

        test=true;	 
	   
         for i= 1, Fractal, 1 do
		
		     if  source.low[x] > source.low[x+i]
			 or  source.low[x] > source.low[x-i]
			 then
			 test=false;
			 end
			
		 end	
	   
	      if test then
			  if Show ~= "Overlay" then
			  down:set(x, source.low[x], "\225");
			  end
			  DOWN = source.low[x]; 
	
			  down_signal[period]=1;			  
		  end
	   
 

 
		  
		  if UP == nil or DOWN == nil then
		  return;
		  end
		  
		 if core.crossesOver (source.close, UP, period ) then   
		  TREND = true;
		 elseif core.crossesUnder (source.close, DOWN, period ) then   
		  TREND = false;
		 end
		 
		if ShowType ~= "Fractal" then
		  if TREND then
		  open:setColor(period, U);
		  elseif not TREND then
		  open:setColor(period, D);
		  end
        end
		
		
	if Signal_Execution~= "Live" then
	period=period-1;	 
	end
	

    for id=1, Number, 1 do
    Signal_Logic (id, period);
	end
    
end


