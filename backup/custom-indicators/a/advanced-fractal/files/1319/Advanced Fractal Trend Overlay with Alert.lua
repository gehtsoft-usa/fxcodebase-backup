function Signal_Logic (id, period)
 
  
	if period < source:first()
	then
	return;
	end
	
	 
	    if id== 1  then   
			if  up_signal[period]== 1			 
			then     
         
                Alert[id][period]= 1;	
			else	
                Alert[id][period]= 0;	 	            
	        end
			
	    end
		
		
		if id== 2   then  
			if  down_signal[period ]== 1	
			then     
         
                Alert[id][period]= 1;	
			else	
                Alert[id][period]= 0;	 	            
	        end
			
	    end


end

