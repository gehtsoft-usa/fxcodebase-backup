 function Calculate(period, mode)
 
   
	
	 rsi1:update(mode);
	 rsi2:update(mode);

	 if   period < first then
	return;
	end
	
	RSI1[period]= rsi1.DATA[period];
	RSI2[period]= rsi2.DATA[period];
 
 end
 

