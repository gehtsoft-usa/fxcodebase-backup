-- Indicator calculation routine
function Update(period, mode)

 
 
    MA1:update(mode);
    MA2:update(mode);
	MA3:update(mode);
	
	
    if period < first then
	return;
	end
	
	
	 if source[period]> MA3.DATA[period] 
	 and  MA1.DATA[period]  > MA2.DATA[period]
	 and source[period]> MA1.DATA[period] 
	 and ((period-Reverse(period))<= Period)
	 then	 
	 Oscillator[period]=1;
	 Oscillator:setColor(period, UpColor);
	 elseif  source[period]< MA3.DATA[period]
	 and  MA1.DATA[period]  < MA2.DATA[period]
	 and source[period]< MA1.DATA[period]
     and ((period-Reverse(period))<= Period)	 
	 then
	 Oscillator[period]=-1;
	 Oscillator:setColor(period, DownColor);
	 else	
     Oscillator[period]=0;
	  Oscillator:setColor(period, NeutralColor);
	 end			  
	 
	 
	 if Live~= "Live" then
	period=period-1;
	Shift=1;
	else
	Shift=0;
	end
	
	
     if period < first then
	 return;
	 end
	
    Activate (1, period)
end




function Activate (id, period)


  
   
   
  
  
	  if id == 1  and ON[id]  then
	  
	       
			if  Oscillator[period]== 1
			and  Oscillator[period-1]~= 1
			then
			           
						    
          
						   
			
			 D[id] = nil;
						   
							  if U[id]~=source:serial(period) 
							  and period == source:size()-1-Shift
							  and not FIRST 
							  and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							  then
							  
							  U[id]=source:serial(period);
							  SoundAlert(Up[id]);
							  EmailAlert(  Label[id], " Cross Over ");
							  SendAlert( Label[id]," Crossed over "); 
							  Pop(Label[id], " Cross Over ", period );  
							  OnlyOnceFlag=false;
							  end
							  
			elseif  Oscillator[period]== -1
			and  Oscillator[period-1]~= -1
            then			
			
			             
						   
		     U[id] = nil;
		   
			                 if  D[id]~=source:serial(period)
							 and period == source:size()-1-Shift
							 and not FIRST 
							 and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							 then							
							 D[id]=source:serial(period);
							 SoundAlert(Down[id]);			 
							 EmailAlert( Label[id] , " Cross Under ");								 
							 Pop(Label[id], " Cross Under ", period );  	
							 SendAlert( Label[id]," Crossed under ");
							 OnlyOnceFlag=false;
			                 end			   
	         end
			
	  
	 
	  end
	  
		   
        if FIRST then
        FIRST=false;      
        end		

end


