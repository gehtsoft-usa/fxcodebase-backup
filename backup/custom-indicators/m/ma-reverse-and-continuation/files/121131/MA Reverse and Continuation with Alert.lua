function Reverse(period)

local First=0;
local Second=0;

	for i= period, first, -1 do 

		if source[period]> MA1.DATA[period]  
		and source[i]< MA1.DATA[i]
		then
		First=i;
		break;
		end


		if source[period]< MA1.DATA[period]  
		and source[i]> MA1.DATA[i]
		then
		First=i;
		break;
		end

	  
	end
	
	
	if First ==0 then
	return Second;
	end
	
	
	for i= First, first, -1 do 

		if source[First]> MA1.DATA[First]  
		and source[i]< MA1.DATA[i]
		then
		Second=i;
		break;
		end


		if source[First]< MA1.DATA[First]  
		and source[i]> MA1.DATA[i]
		then
		Second=i;
		break;
		end

	  
	end


 


 return Second;

