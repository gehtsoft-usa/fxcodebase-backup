function Init()
    indicator:name("Quadruple Exponential Moving Average indicator");
    indicator:description("Quadruple Exponential Moving Average indicator");
    indicator:requiredSource(core.Tick);
    indicator:type(core.Indicator);

    indicator.parameters:addGroup("Calculation");
    indicator.parameters:addInteger("Period", "Period", "", 14);
    indicator.parameters:addString("Method", "Method", "", "MVA");
    indicator.parameters:addStringAlternative("Method", "MVA", "", "MVA");
    indicator.parameters:addStringAlternative("Method", "EMA", "", "EMA");
    indicator.parameters:addStringAlternative("Method", "KAMA", "", "KAMA");
    indicator.parameters:addStringAlternative("Method", "Wilder", "", "Wilder");
    indicator.parameters:addStringAlternative("Method", "LWMA", "", "LWMA");
    indicator.parameters:addStringAlternative("Method", "SineWMA", "", "SineWMA");
    indicator.parameters:addStringAlternative("Method", "TriMA", "", "TriMA");
    indicator.parameters:addStringAlternative("Method", "LSMA", "", "LSMA");
    indicator.parameters:addStringAlternative("Method", "SMMA", "", "SMMA");
    indicator.parameters:addStringAlternative("Method", "HMA", "", "HMA");
    indicator.parameters:addStringAlternative("Method", "ZeroLagEMA", "", "ZeroLagEMA");
    indicator.parameters:addStringAlternative("Method", "DEMA", "", "DEMA");
    indicator.parameters:addStringAlternative("Method", "T3", "", "T3");
    indicator.parameters:addStringAlternative("Method", "ITrend", "", "ITrend");
    indicator.parameters:addStringAlternative("Method", "Median", "", "Median");
    indicator.parameters:addStringAlternative("Method", "GeoMean", "", "GeoMean");
    indicator.parameters:addStringAlternative("Method", "REMA", "", "REMA");
    indicator.parameters:addStringAlternative("Method", "ILRS", "", "ILRS");
    indicator.parameters:addStringAlternative("Method", "IE/2", "", "IE/2");
    indicator.parameters:addStringAlternative("Method", "TriMAgen", "", "TriMAgen");
    indicator.parameters:addStringAlternative("Method", "JSmooth", "", "JSmooth");

    indicator.parameters:addGroup("Style");
    indicator.parameters:addColor("clr", "Color", "Color", core.rgb(0, 255, 0));
    indicator.parameters:addInteger("widthLinReg", "Line width", "Line width", 1, 1, 5);
    indicator.parameters:addInteger("styleLinReg", "Line style", "Line style", core.LINE_SOLID);
    indicator.parameters:setFlag("styleLinReg", core.FLAG_LINE_STYLE);
end

local first;
local source = nil;
local Period;
local Method;
local MA1, MA2, MA3, MA4, MA5;
local QEMA=nil;

function Prepare(nameOnly)
    source = instance.source;
    Period=instance.parameters.Period;
    Method=instance.parameters.Method;
    first = source:first()+2;
	
    local name = profile:id() .. "(" .. source:name() .. ", " .. instance.parameters.Period .. ", " .. instance.parameters.Method .. ")";
    instance:name(name);
    if nameOnly then
        return;
    end
	
    assert(core.indicators:findIndicator("AVERAGES") ~= nil, "Please, download and install AVERAGES.LUA indicator");    
    
        MA1 = core.indicators:create("AVERAGES", source, Method, Period, false);
        MA2 = core.indicators:create("AVERAGES", MA1.DATA, Method, Period, false);
        MA3 = core.indicators:create("AVERAGES", MA2.DATA, Method, Period, false);
        MA4 = core.indicators:create("AVERAGES", MA3.DATA, Method, Period, false);
        MA5 = core.indicators:create("AVERAGES", MA4.DATA, Method, Period, false);
        
        first= MA5.DATA:first();
    QEMA = instance:addStream("QEMA", core.Line, name .. ".QEMA", "QEMA", instance.parameters.clr, first);
    QEMA:setWidth(instance.parameters.widthLinReg);
    QEMA:setStyle(instance.parameters.styleLinReg);
    QEMA:setPrecision(math.max(2, instance.source:getPrecision()));	
	
end

function Update(period, mode)
 
    MA1:update(mode);
    MA2:update(mode);
    MA3:update(mode);
    MA4:update(mode);
    MA5:update(mode);
	
	if (period<=first) then
	return;
	end
	
    QEMA[period]=5*MA1.DATA[period]-10*MA2.DATA[period]+10*MA3.DATA[period]-5*MA4.DATA[period]+MA5.DATA[period];
   
end


