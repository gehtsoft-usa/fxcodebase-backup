-- Indicator calculation routine
function Update(period)
    if period< first 
	then
	return;
	end
	
        local sx, sy, sxy, sx2, i, t, a, b, tsf;
        t = N;
        sx = 0;
        sy = 0;
        sxy = 0;
        sx2 = 0;
        for i = period - N, period - 1, 1 do
            sy = sy + source[i];
            sx = sx + t;
            sx2 = sx2 + t * t;
            sxy = sxy + source[i] * t;
            t = t - 1;
        end
        b = (N * sxy - sx * sy) / (N * sx2 - sx * sx);
        a = (sy - b * sx) / N;
        tsf = a + b;
        FO[period] = (source[period] - tsf) / source[period] * 100;
		
		
	if Live~= "Live" then
	period=period-1;
	Shift=1;
	else
	Shift=0;
	end
	
	
     if period < first then
	 return;
	 end
	
    Activate (1, period)
 
end



function Activate (id, period)


   Alert[id][period]=0;
   
   
  
  
	  if id == 1  and ON[id]  then
	  
	       
			if  FO[period] > 0
			and   FO[period-1] <= 0
			then
			           
						    
         
                Alert[id][period]= 1;	
 				AlertLevel[id][period]= 0
						   
			
			 D[id] = nil;
						   
							  if U[id]~=source:serial(period) 
							  and period == source:size()-1-Shift
							  and not FIRST 
							  and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							  then
							  
							  U[id]=source:serial(period);
							  SoundAlert(Up[id]);
							  EmailAlert(  Label[id], " Cross Over ", period);
							  SendAlert( Label[id]," Crossed over ", period); 
							  Pop(Label[id], " Cross Over ", period );  
							  OnlyOnceFlag=false;
							  end
							  
			elseif  FO[period] < 0
			and   FO[period-1] >= 0
            then			
			
			            			 
			                Alert[id][period]= -1;	
							AlertLevel[id][period]= 0
						   
		     U[id] = nil;
		   
			                 if  D[id]~=source:serial(period)
							 and period == source:size()-1-Shift
							 and not FIRST 
							 and  (not OnlyOnce or (OnlyOnce and OnlyOnceFlag~= false))
							 then							
							 D[id]=source:serial(period);
							 SoundAlert(Down[id]);			 
							 EmailAlert( Label[id] , " Cross Under ", period);								 
							 Pop(Label[id], " Cross Under ", period );  	
							 SendAlert( Label[id]," Crossed under ", period);
							 OnlyOnceFlag=false;
			                 end			   
	         end
			
	  
	 
	  end
	  
		   
        if FIRST then
        FIRST=false;      
        end		

end


