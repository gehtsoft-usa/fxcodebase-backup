local first;
local source = nil;
local Period;
	
-- Routine
 function Prepare(nameOnly)   
 
    
	Period=instance.parameters.Period;
	source = instance.source
 
    local name = profile:id() .. "(" ..  instance.source:name().. "," ..  Period  .. ")";
    instance:name(name); 


    if   (nameOnly) then
        return;
    end


	first=source:first()+Period ; 
	
	
	--Stream = instance:addInternalStream(0, 0);
 
	
	
    Line = instance:addStream("Line", core.Line, name, "Line", instance.parameters.color, first );
    Line:setPrecision(math.max(2, instance.source:getPrecision()));
    Line:setWidth(instance.parameters.width);
    Line:setStyle(instance.parameters.style);
    Line:addLevel(0);	
 
end


function Update(period, mode) 

	if period <= first
	or  not source:hasData(period) 
	then
	return;
	end
	  
	  	
	Line[period]= hanningWindowMovingAverage(period, source, Period);
end


-- Function for Hanning Window Moving Average
function hanningWindowMovingAverage(period, data, windowSize)
        local result;

 
        local sum = 0
        local weightSum = 0

        for i =  1, windowSize, 1 do
            local weight = 0.5 * (1 - math.cos(2 * math.pi * (i) / (2 * windowSize)))
            sum = sum + data[period-windowSize+i] * weight
            weightSum = weightSum + weight
        end

        result = sum / weightSum
    

    return result
end

 


